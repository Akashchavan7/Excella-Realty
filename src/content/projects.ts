export function getProject(slug: string) {
  return projects.find((p) => p.slug === slug);
}

export function projectsByStatus(status: ProjectStatus) {
  return projects.filter((p) => p.status === status);
}

export function relatedProjects(project: Project, limit = 3) {
  const score = (p: Project) =>
    (p.neighbourhood && p.neighbourhood === project.neighbourhood ? 3 : 0) +
    (p.collection && p.collection === project.collection ? 2 : 0) +
    (p.status === project.status ? 1 : 0) +
    (p.legacy ? -2 : 0) +
    (p.cover ? 0 : -3);
  return projects
    .filter((p) => p.slug !== project.slug)
    .sort((a, b) => score(b) - score(a))
    .slice(0, limit);
}
